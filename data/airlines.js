export function getAllAirlines(filter = 'ALL') {
  const indian = Object.values(indianAirlines);
  const international = Object.values(internationalAirlines);
  if (filter === 'INDIAN') return indian;
  if (filter === 'INTERNATIONAL') return international;
  return [...indian, ...international];
}

export function getAirlineInfo(iataOrIcao) {
  if (!iataOrIcao) return null;
  const code = iataOrIcao.trim().toUpperCase();
  
  if (indianAirlines[code]) return indianAirlines[code];
  if (internationalAirlines[code]) return internationalAirlines[code];
  
  // Legacy / Merged airline resolution
  if (code === 'UK' || code === 'VTI') return indianAirlines['AI']; // Vistara merged into Air India
  if (code === 'I5' || code === 'IAD') return indianAirlines['IX']; // AIX Connect merged into Air India Express
  
  // Try matching ICAO
  for (const key in indianAirlines) {
    if (indianAirlines[key].icao === code) return indianAirlines[key];
  }
  for (const key in internationalAirlines) {
    if (internationalAirlines[key].icao === code) return internationalAirlines[key];
  }

  // Match 2-char prefix of flight number like 6E205 -> 6E, EY327 -> EY
  const prefix2 = code.slice(0, 2);
  if (prefix2 === 'UK') return indianAirlines['AI'];
  if (prefix2 === 'I5') return indianAirlines['IX'];
  if (indianAirlines[prefix2]) return indianAirlines[prefix2];
  if (internationalAirlines[prefix2]) return internationalAirlines[prefix2];

  const prefix3 = code.slice(0, 3);
  if (prefix3 === 'VTI') return indianAirlines['AI'];
  if (prefix3 === 'IAD') return indianAirlines['IX'];
  for (const key in indianAirlines) {
    if (indianAirlines[key].icao === prefix3) return indianAirlines[key];
  }
  for (const key in internationalAirlines) {
    if (internationalAirlines[key].icao === prefix3) return internationalAirlines[key];
  }

  return null;
}
